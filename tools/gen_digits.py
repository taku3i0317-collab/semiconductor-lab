N = 8


def grid(rows):
    return [[1 if c == "#" else 0 for c in r] for r in rows]


def shift(g, dx, dy):
    o = [[0] * N for _ in range(N)]
    for y in range(N):
        for x in range(N):
            if g[y][x] and 0 <= x + dx < N and 0 <= y + dy < N:
                o[y + dy][x + dx] = 1
    return o


def thicken(g, rnd):
    o = [r[:] for r in g]
    d = rnd.choice([(1, 0), (0, 1)])
    for y in range(N):
        for x in range(N):
            if g[y][x] and 0 <= x + d[0] < N and 0 <= y + d[1] < N:
                o[y + d[1]][x + d[0]] = 1
    return o


def noise(g, rnd):
    o = [r[:] for r in g]
    for _ in range(rnd.randint(1, 2)):
        x, y = rnd.randrange(N), rnd.randrange(N)
        o[y][x] = 1 - o[y][x]
    return o


def variants(g, rnd, count):
    out = []
    for _ in range(count):
        v = shift(g, rnd.randint(-1, 1), rnd.randint(-1, 1))
        if rnd.random() < 0.4:
            v = thicken(v, rnd)
        if rnd.random() < 0.6:
            v = noise(v, rnd)
        out.append(sum(v, []))
    return out


def main():
    rnd = random.Random(20261021)
    train, test = [], []
    for digit, tpls in TEMPLATES.items():
        for t in tpls:
            g = grid(t)
            assert len(g) == N and all(len(r) == N for r in g), (digit, t)
            train += [[v, digit] for v in variants(g, rnd, 40)]
            test += [[v, digit] for v in variants(g, rnd, 10)]
    rnd.shuffle(train)
    rnd.shuffle(test)
    out = pathlib.Path("src/main/resources/data/semiconductor-lab/ai/digits.json")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps({"license": "CC0-1.0", "note": "Semiconductor Lab hand-drawn 8x8 digits, augmented by tools/gen_digits.py (seed 20261021)",
                               "size": N, "train": train, "test": test}, separators=(",", ":")) + "\n", encoding="utf-8")
    print(out, "train", len(train), "test", len(test))


if __name__ == "__main__":
    main()
